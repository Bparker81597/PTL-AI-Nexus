const characterReference = (characterId: string) => sampleAssets.filter((asset) => asset.characterId === characterId);
const assetCountFor = (characterId: string) =>
  sampleAssets.filter((asset) => asset.characterIds?.includes(characterId) || asset.characterId === characterId).length;
const slugFor = (name: string) => name.toLowerCase().replaceAll(" ", "-");
const relationshipRecords = (sourceCharacterId: string, closestFriendId: string) =>
  crewCharacterIds
