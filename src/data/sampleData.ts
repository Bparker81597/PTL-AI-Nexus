const readiness = (states: Record<string, "missing" | "started" | "in-progress" | "ready" | "complete">) =>
  Object.entries(states).map(([category, state]) => ({ category: category as CharacterReadinessCategory, state, updatedAt: createdAt }));
const expressionRecords = (characterId: string, names: string[], accent: string) =>
  names.map((name, index) => ({
    id: `expr-${characterId}-${slugFor(name)}`,
    name,
    emotion: name,
    status: index < 3 ? "approved" as const : "review" as const,
    prompt: `${name} expression for ${characterId.replace("char-", "")}, consistent PTL Crew design, ${accent} accent palette.`,
    animationNotes: `${name} should read clearly in a medium shot and stay child-friendly.`,
    usageNotes: index < 2 ? "Core pilot expression." : "Secondary expression for later refinement.",
    sceneIds: index < 2 ? ["scene-wonder-question"] : [],
    createdAt,
    updatedAt: createdAt,
  }));
const outfitRecords = (characterId: string, outfits: Array<{ name: string; category: "default" | "school" | "adventure" | "seasonal" | "sleepwear" | "special-event" | "weather" | "costume"; description: string; accessories?: string[]; footwear?: string; palette: string[] }>) =>
  outfits.map((outfit, index) => ({
    id: `outfit-${characterId}-${slugFor(outfit.name)}`,
    name: outfit.name,
    category: outfit.category,
    description: outfit.description,
    accessories: outfit.accessories ?? [],
    footwear: outfit.footwear,
    palette: outfit.palette,
    status: index === 0 ? "approved" as const : "review" as const,
    continuityNotes: "Keep proportions, colors, and signature details consistent across storyboard and animation.",
    episodeIds: [activeEpisodeId],
    sceneIds: index === 0 ? crewSceneIds : [],
  }));
const animationRecords = (characterId: string, names: Array<{ name: string; category: "idle" | "walk" | "run" | "jump" | "wave" | "laugh" | "cry" | "dance" | "point" | "celebrate" | "other"; notes: string }>) =>
  names.map((item, index) => ({
    id: `anim-${characterId}-${slugFor(item.name)}`,
    name: item.name,
    category: item.category,
    status: index < 2 ? "review" as const : "draft" as const,
    notes: item.notes,
    sceneIds: index < 2 ? ["scene-clubhouse-meet"] : [],
    updatedAt: createdAt,
  }));
const propRecords = (characterId: string, props: Array<{ name: string; importance: "minor" | "recurring" | "signature"; description: string }>) =>
  props.map((prop) => ({
    id: `prop-${characterId}-${slugFor(prop.name)}`,
    name: prop.name,
    importance: prop.importance,
    description: prop.description,
    ownership: characterId,
    continuityNotes: "Prop should reinforce the character role without overwhelming the scene.",
    sceneIds: crewSceneIds.slice(0, 2),
    status: prop.importance === "signature" ? "approved" as const : "review" as const,
  }));
const continuityRules = (characterId: string, rules: Array<{ title: string; rule: string; category: "appearance" | "outfit" | "prop" | "behavior" | "voice" | "animation" | "relationship" | "story"; severity: "informational" | "important" | "critical" }>) =>
  rules.map((rule) => ({
    id: `rule-${characterId}-${slugFor(rule.title)}`,
    title: rule.title,
    rule: rule.rule,
    category: rule.category,
    severity: rule.severity,
    active: true,
    sceneIds: crewSceneIds,
    notes: "Production continuity rule for PTL Crew pilot work.",
  }));
